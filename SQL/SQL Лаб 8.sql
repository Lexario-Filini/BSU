GO

-- 1. Распределение по эффективности
SELECT 
    P.[Название],
    T.[Сумма_товарооборота],
    SUM(V.[Сумма]) AS [Общие_издержки],
    CAST(SUM(V.[Сумма]) / T.[Сумма_товарооборота] * 100 AS DECIMAL(10,2)) AS [Уровень_издержек_%],
    DENSE_RANK() OVER (ORDER BY (SUM(V.[Сумма]) / T.[Сумма_товарооборота]) ASC) AS [Место_в_рейтинге]
FROM [Подразделения] P
JOIN [Ведомость_издержек] V ON P.[Код_подразделения] = V.[Код_подразделения]
JOIN [Товарооборот_подразделений] T ON P.[Код_подразделения] = T.[Код_подразделения]
GROUP BY P.[Название], T.[Сумма_товарооборота];

-- 2.Основные расходы
WITH CostStats AS (
    SELECT 
        [Код_подразделения],
        [Код_статьи],
        SUM([Сумма]) AS ItemTotal,
        SUM(SUM([Сумма])) OVER(PARTITION BY [Код_подразделения]) AS DeptTotal
    FROM [Ведомость_издержек]
    GROUP BY [Код_подразделения], [Код_статьи]
)
SELECT P.[Название], S.[Наименование], 
       CAST((ItemTotal / DeptTotal * 100) AS DECIMAL(10,2)) AS [Доля_в_затратах_%]
FROM CostStats CS
JOIN [Подразделения] P ON CS.[Код_подразделения] = P.[Код_подразделения]
JOIN [Статьи_расхода] S ON CS.[Код_статьи] = S.[Код_статьи]
WHERE (ItemTotal / DeptTotal) > 0.3;

-- 3. Распределение по уровню затрат
SELECT [Название],
    CASE 
        WHEN (SUM([Сумма]) / [Сумма_товарооборота] * 100) < 5 THEN N'Экономное'
        WHEN (SUM([Сумма]) / [Сумма_товарооборота] * 100) BETWEEN 5 AND 10 THEN N'Среднее'
        ELSE N'Высокие издержки'
    END AS [Категория_эффективности]
FROM [Подразделения] P
JOIN [Ведомость_издержек] V ON P.[Код_подразделения] = V.[Код_подразделения]
JOIN [Товарооборот_подразделений] T ON P.[Код_подразделения] = T.[Код_подразделения]
GROUP BY [Название], [Сумма_товарооборота];

-- 4. Повышение цен на транспорт
UPDATE V
SET V.[Сумма] = V.[Сумма] * 1.10
FROM [Ведомость_издержек] V
JOIN [Товарооборот_подразделений] T ON V.[Код_подразделения] = T.[Код_подразделения]
WHERE V.[Код_статьи] = 10 AND T.[Сумма_товарооборота] > 400000;
SELECT * FROM [Ведомость_издержек];

-- 5. Итог расходов по подразделениям
SELECT 
    [Дата_ведомости],
    [Номер_ведомости],
    [Код_подразделения],
    [Сумма],
    SUM([Сумма]) OVER (PARTITION BY [Код_подразделения] ORDER BY [Дата_ведомости]) AS [Нарастающий_итог]
FROM [Ведомость_издержек];

-- 6. Отсутствующие статьи расходов
SELECT 
    P.[Название] AS [Подразделение], 
    S.[Наименование] AS [Отсутствующая_статья_расхода]
FROM (
    SELECT [Код_подразделения], [Код_статьи]
    FROM [Подразделения] CROSS JOIN [Статьи_расхода]
    EXCEPT
    SELECT [Код_подразделения], [Код_статьи]
    FROM [Ведомость_издержек]
) AS MissingPairs
JOIN [Подразделения] P ON MissingPairs.[Код_подразделения] = P.[Код_подразделения]
JOIN [Статьи_расхода] S ON MissingPairs.[Код_статьи] = S.[Код_статьи]
ORDER BY P.[Название];

-- 7. Средние расходы
WITH AllCosts AS (
    SELECT V.*, S.[Наименование],
           AVG(V.[Сумма]) OVER(PARTITION BY V.[Код_статьи]) AS [Средние_расходы]
    FROM [Ведомость_издержек] V
    JOIN [Статьи_расхода] S ON V.[Код_статьи] = S.[Код_статьи]
)
SELECT * FROM AllCosts
WHERE [Сумма] > [Средние_расходы];

-- 8. Самые большие расходы
SELECT [Название], [Наименование], [Максимальная_сумма]
FROM (
    SELECT P.[Название], S.[Наименование], SUM(V.[Сумма]) as Максимальная_сумма,
           ROW_NUMBER() OVER(PARTITION BY P.[Код_подразделения] ORDER BY SUM(V.[Сумма]) DESC) as RN
    FROM [Ведомость_издержек] V
    JOIN [Подразделения] P ON V.[Код_подразделения] = P.[Код_подразделения]
    JOIN [Статьи_расхода] S ON V.[Код_статьи] = S.[Код_статьи]
    GROUP BY P.[Название], S.[Наименование], P.[Код_подразделения]
) AS TopCosts WHERE RN = 1;

-- 9. Расходы по основным направлениям
SELECT [Название],
    ISNULL(SUM(CASE WHEN [Код_статьи] = 10 THEN [Сумма] END), 0) AS [Транспорт],
    ISNULL(SUM(CASE WHEN [Код_статьи] = 20 THEN [Сумма] END), 0) AS [Аренда],
    ISNULL(SUM(CASE WHEN [Код_статьи] = 30 THEN [Сумма] END), 0) AS [Зарплата]
FROM [Ведомость_издержек] V
JOIN [Подразделения] P ON V.[Код_подразделения] = P.[Код_подразделения]
GROUP BY [Название];

-- 10. Примечания
SELECT 
    P.[Название] AS [Подразделение],
    COUNT(V.[Код_записи]) AS [Количество_ведомостей],
    SUM(V.[Сумма]) AS [Общая_сумма],
    ISNULL(STRING_AGG(CAST(V.[Примечание] AS NVARCHAR(MAX)), '; '), N'Примечаний нет') AS [Все_пояснения]
FROM [Подразделения] P
LEFT JOIN [Ведомость_издержек] V ON P.[Код_подразделения] = V.[Код_подразделения]
GROUP BY P.[Название];