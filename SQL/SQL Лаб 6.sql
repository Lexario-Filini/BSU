CREATE OR ALTER VIEW [Представление_Расписание_ФИО] AS
SELECT 
    A.[Код_записи], 
    A.[День_недели], 
    A.[Номер_пары], 
    B.[ФИО] AS [Преподаватель],
    A.[Количество_студентов]
FROM [Расписание] AS A
LEFT JOIN [Преподаватели] AS B ON A.[Код_преподавателя] = B.[Код_преподавателя];
