class SportsCenter {

    _objs = [];

    constructor(Objs) {
        this.addAll(Objs);
    }

    _isValidDate(value) {
        return value instanceof Date && !isNaN(value.getTime());
    }

    _isValidPartial(Obj) {
        if (Obj === null || typeof Obj !== "object" || Array.isArray(Obj)) {
            return false;
        }

        const allowedFields = [
            "description", "photoLink", "activity", "date",
            "time", "address", "type", "audience", "trainer", "capacity"
        ];

        for (let key of Object.keys(Obj)) {
            if (!allowedFields.includes(key)) {
                return false;
            }
        }

        if ("description" in Obj &&
            (typeof Obj.description !== "string" ||
            Obj.description.length === 0 ||
            Obj.description.length >= 200)) {
            return false;
        }

        if ("photoLink" in Obj && typeof Obj.photoLink !== "string") {
            return false;
        }

        const stringFields = [
            "activity", "date", "time", "address",
            "type", "audience", "trainer"
        ];

        for (let field of stringFields) {
            if (field in Obj &&
                (typeof Obj[field] !== "string" || Obj[field].trim() === "")) {
                return false;
            }
        }

        if ("capacity" in Obj &&
            (!Number.isInteger(Obj.capacity) || Obj.capacity < 1)) {
            return false;
        }

        return true;
    }

    getObjs(skip = 0, top = 10, filterConfig = {}) {
        if (!Number.isInteger(skip) || skip < 0 ||
            !Number.isInteger(top) || top < 0) {
            return [];
        }

        if (filterConfig === null ||
            typeof filterConfig !== "object" ||
            Array.isArray(filterConfig)) {
            return [];
        }

        let result = [...this._objs];

        const sortBy = filterConfig.sortBy || "createdAt";
        const sortOrder = filterConfig.sortOrder || "asc";

        const allowedFields = [
            "id", "description", "createdAt", "author", "photoLink",
            "activity", "date", "time", "address", "type",
            "audience", "trainer", "capacity"
        ];

        if (!allowedFields.includes(sortBy) ||
            !["asc", "desc"].includes(sortOrder)) {
            return [];
        }

        for (let key of Object.keys(filterConfig)) {
            if (key === "sortBy" || key === "sortOrder") {
                continue;
            }

            if (!allowedFields.includes(key)) {
                return [];
            }

            result = result.filter(obj => {
                if (obj[key] instanceof Date) {
                    return obj[key].getTime() === new Date(filterConfig[key]).getTime();
                }

                if (typeof obj[key] === "string") {
                    return obj[key].toLowerCase().includes(
                        String(filterConfig[key]).toLowerCase()
                    );
                }

                return obj[key] === filterConfig[key];
            });
        }

        result.sort((a, b) => {
            let valueA = a[sortBy];
            let valueB = b[sortBy];

            if (valueA instanceof Date) {
                valueA = valueA.getTime();
                valueB = valueB.getTime();
            }

            if (typeof valueA === "string") {
                valueA = valueA.toLowerCase();
                valueB = valueB.toLowerCase();
            }

            if (valueA < valueB) return sortOrder === "asc" ? -1 : 1;
            if (valueA > valueB) return sortOrder === "asc" ? 1 : -1;
            return 0;
        });

        return result.slice(skip, skip + top);
    }

    getObj(id) {
        return this._objs.find(obj => obj.id === id) || null;
    }

    validateObj(Obj) {
        if (Obj === null || typeof Obj !== "object" || Array.isArray(Obj)) {
            return false;
        }

        if (typeof Obj.id !== "string" || Obj.id.trim() === "") {
            return false;
        }

        if (typeof Obj.description !== "string" ||
            Obj.description.length === 0 ||
            Obj.description.length >= 200) {
            return false;
        }

        if (!this._isValidDate(Obj.createdAt)) {
            return false;
        }

        if (typeof Obj.author !== "string" || Obj.author.trim() === "") {
            return false;
        }

        return this._isValidPartial({
            description: Obj.description,
            photoLink: Obj.photoLink ?? "",
            activity: Obj.activity,
            date: Obj.date,
            time: Obj.time,
            address: Obj.address,
            type: Obj.type,
            audience: Obj.audience,
            trainer: Obj.trainer,
            capacity: Obj.capacity
        });
    }

    addObj(Obj) {
        if (!this.validateObj(Obj)) {
            return false;
        }

        if (this.getObj(Obj.id)) {
            return false;
        }

        this._objs.push(Obj);
        return true;
    }

    editObj(id, Obj) {
        const existing = this.getObj(id);

        if (!existing || !this._isValidPartial(Obj)) {
            return false;
        }

        Object.assign(existing, Obj);
        return true;
    }

    removeObj(id) {
        const index = this._objs.findIndex(obj => obj.id === id);

        if (index === -1) {
            return false;
        }

        this._objs.splice(index, 1);
        return true;
    }

    addAll(Objs) {
        if (!Array.isArray(Objs)) {
            return [];
        }

        let added = [];

        for (let Obj of Objs) {
            if (this.addObj(Obj)) {
                added.push(Obj);
            }
        }

        return added;
    }

    clear() {
        this._objs = [];
    }

    getCount() {
        return this._objs.length;
    }
}


